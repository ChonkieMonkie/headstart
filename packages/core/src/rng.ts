// Seeded random numbers. Crates are opened with a generator seeded from the
// crate itself, so a result can always be reproduced and checked later.

/** Returns a number in [0, 1). */
export type Rng = () => number;

/** Hashes a string into four 32-bit words (the cyrb128 hash). */
export function hashSeed(input: string): [number, number, number, number] {
  let h1 = 1779033703;
  let h2 = 3144134277;
  let h3 = 1013904242;
  let h4 = 2773480762;
  for (let i = 0; i < input.length; i++) {
    const k = input.charCodeAt(i);
    h1 = h2 ^ Math.imul(h1 ^ k, 597399067);
    h2 = h3 ^ Math.imul(h2 ^ k, 2869860233);
    h3 = h4 ^ Math.imul(h3 ^ k, 951274213);
    h4 = h1 ^ Math.imul(h4 ^ k, 2716044179);
  }
  h1 = Math.imul(h3 ^ (h1 >>> 18), 597399067);
  h2 = Math.imul(h4 ^ (h2 >>> 22), 2869860233);
  h3 = Math.imul(h1 ^ (h3 >>> 17), 951274213);
  h4 = Math.imul(h2 ^ (h4 >>> 19), 2716044179);
  h1 ^= h2 ^ h3 ^ h4;
  h2 ^= h1;
  h3 ^= h1;
  h4 ^= h1;
  return [h1 >>> 0, h2 >>> 0, h3 >>> 0, h4 >>> 0];
}

const rotl = (x: number, k: number) => (x << k) | (x >>> (32 - k));

/** A fast, well-distributed generator (xoshiro128**) seeded from a string. */
export function createRng(seed: string): Rng {
  let [a, b, c, d] = hashSeed(seed);
  if ((a | b | c | d) === 0) a = 1; // the all-zero state never changes

  return () => {
    const result = Math.imul(rotl(Math.imul(b, 5), 7), 9);
    const t = b << 9;
    c ^= a;
    d ^= b;
    b ^= c;
    a ^= d;
    c ^= t;
    d = rotl(d, 11);
    return (result >>> 0) / 4294967296;
  };
}

/** A whole number in [0, size). */
export function randomIndex(rng: Rng, size: number): number {
  return Math.min(size - 1, Math.floor(rng() * size));
}
